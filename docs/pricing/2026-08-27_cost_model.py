# -*- coding: utf-8 -*-
"""GT bottom-up cost model — prices & doses from GT_Summer_Menu_2026.xls."""

# ---- מחירון מהקובץ (₪ לליטר / לק"ג) ----
GT      = 65/1000        # תרכיז GT
PUREE   = 55/1000        # מחית פרי
MATCHA  = 1080/1000      # ₪/גרם
UBE     = 350/1000       # ₪/גרם
LEMONADE= 3/1000
COCO_CR = 14/1000        # קרם קוקוס
COCO_W  = 10/1000        # מי קוקוס
MILK    = 8/1000
ESPRESSO= 1.00           # מפורש בקובץ
TONIC   = 1.50           # מפורש בקובץ
OJ      = 2.00           # מפורש בקובץ

# ---- הנחות (חסרים בקובץ; נבחר הזול/הקטן לפי הנחיית Tom) ----
CUP     = 350            # מ"ל — הכוס הקטנה
BASE    = CUP*2/3        # ⅔ כוס = 233 מ"ל
CREAM38 = 22/1000        # שמנת 38%
APPLE   = 7/1000         # מיץ תפוחים
LYCHEE  = 12/1000        # מי ליצ'י
AGAVE   = 30/1000        # סירופ אגבה
# גרניש, קרח, מים, סודה — לא נכללים

# קצף קר מוכן, לפי מתכוני ההכנה בקובץ (ל-1 ליטר מוכן)
FOAM_MILK  = (350*CREAM38 + 650*MILK)/1000/2   # שמנת 350 מ"ל + חלב; הקצפה מכפילה נפח ⟶ ÷2
FOAM_COCO  = (300*COCO_CR)/1000/2            # קרם קוקוס 300 מ"ל; הקצפה מכפילה נפח ⟶ ÷2
FOAM_YIELD = 2   # הקצפה מכפילה נפח (Tom)
FOAM_ML    = 70                              # מנת קצף

# תוספות טעם (אין מתכון בקובץ — הנחה)
FLAV = {"וניל":0.30, "פיסטוק":1.20, "שומשום שחור":0.80, "קפה":ESPRESSO, "בננה":0.50}

def r(x): return round(x, 2)

M = {}   # name -> (cost, breakdown)
def add(name, parts):
    M[name] = (r(sum(v for _, v in parts)), parts)

# 1 · חליטות קרות — 50 מ"ל GT
for n in ["חליטת היביסקוס וליים","חליטת קמומיל ותפוח","חליטה מדברית","חליטת סנצ'ה ופסיפלורה",
          "חליטת תה ירוק וליים","חליטת תה ירוק ולמון גראס","חליטת יסמין וליצ'י"]:
    add(n, [("50 מ\"ל GT", 50*GT)])

# 2 · לימונדות — 50 מ"ל GT + לימונדה
for n in ["לימונדת היביסקוס וליים","לימונדה מדברית","לימונדת צ'אי מסאלה"]:
    add(n, [("50 מ\"ל GT", 50*GT), (f"{BASE:.0f} מ\"ל לימונדה", BASE*LEMONADE)])

# 3 · Fruitea/Signature — 40 GT + 40 מחית/מיץ
add("חליטת אפרסק מדברית",  [("40 מ\"ל GT",40*GT), ("40 מ\"ל מחית אפרסק",40*PUREE)])
add("חליטת תות לואיזה",     [("40 מ\"ל GT",40*GT), ("40 מ\"ל מחית תות",40*PUREE)])
add("חליטת מנגו סנצ'ה",     [("40 מ\"ל GT",40*GT), ("40 מ\"ל מנגו",40*PUREE)])
add("חליטת תפוח היביסקוס",  [("40 מ\"ל GT",40*GT), ("40 מ\"ל מיץ תפוחים",40*APPLE)])

# 4 · גזוז — 40 GT + 40 מיץ
add("גזוז יסמין וליצ'י",   [("40 מ\"ל GT",40*GT), ("40 מ\"ל מי ליצ'י",40*LYCHEE)])
add("גזוז מדברי ואפרסק",   [("40 מ\"ל GT",40*GT), ("40 מ\"ל מחית אפרסק",40*PUREE)])
add("גזוז היביסקוס ותפוח", [("40 מ\"ל GT",40*GT), ("40 מ\"ל מיץ תפוחים",40*APPLE)])

# 5 · אייס מאצ'ה — 1.8 גר' מאצ'ה + ⅔ חלב + קצף
MB = [("מאצ'ה 1.8 גר'",1.8*MATCHA), (f"{BASE:.0f} מ\"ל חלב",BASE*MILK), ("70 מ\"ל קצף חלבי",FOAM_ML*FOAM_MILK)]
add("אייס מאצ'ה קלאסי", MB)
for n, ing in [("אייס מאצ'ה מנגו","מנגו"),("אייס מאצ'ה תות","מחית תות"),("אייס מאצ'ה אפרסק","מחית אפרסק")]:
    add(n, MB + [(f"40 מ\"ל {ing}",40*PUREE)])
add("אייס מאצ'ה מסאלה", MB + [("40 מ\"ל GT מסאלה",40*GT)])
add("מאצ'ה אגבה על הקרח", [("מאצ'ה 1.8 גר'",1.8*MATCHA), ("15 מ\"ל אגבה",15*AGAVE), ("70 מ\"ל קצף חלבי",FOAM_ML*FOAM_MILK)])

# 6 · מאצ'ה טעמים מיוחדים — בסיס קלאסי + טעם
for n, f in [("אייס מאצ'ה וניל","וניל"),("אייס מאצ'ה פיסטוק","פיסטוק"),
             ("אייס מאצ'ה שומשום שחור","שומשום שחור"),("אייס מאצ'ה קפה","קפה"),("אייס מאצ'ה בננה","בננה")]:
    add(n, MB + [(f, FLAV[f])])

# 7 · מאצ'ה קוקוס — 50 מ"ל מאצ'ה + 150 מי קוקוס + 70 קרם קוקוס
CB = [("מאצ'ה 1.8 גר'",1.8*MATCHA), ("150 מ\"ל מי קוקוס",150*COCO_W), ("70 מ\"ל קרם קוקוס",FOAM_ML*FOAM_COCO)]
add("מאצ'ה קוקוס אגבה",  CB + [("15 מ\"ל אגבה",15*AGAVE)])
add("מאצ'ה קוקוס ליצ'י", CB + [("40 מ\"ל מי ליצ'י",40*LYCHEE)])
for n, ing in [("מאצ'ה קוקוס תות","מחית תות"),("מאצ'ה קוקוס מנגו","מנגו"),("מאצ'ה קוקוס אפרסק","מחית אפרסק")]:
    add(n, CB + [(f"40 מ\"ל {ing}",40*PUREE)])

# 8 · צ'אי מסאלה — 50 מ"ל GT
add("אייס צ'אי מסאלה קלאסי",[("50 מ\"ל GT",50*GT), (f"{BASE:.0f} מ\"ל חלב",BASE*MILK), ("70 מ\"ל קצף חלבי",FOAM_ML*FOAM_MILK)])
add("צ'אי מסאלה על הקרח",   [("50 מ\"ל GT",50*GT), ("70 מ\"ל קצף חלבי",FOAM_ML*FOAM_MILK)])
add("דירטי צ'אי",           [("50 מ\"ל GT",50*GT), (f"{BASE:.0f} מ\"ל חלב",BASE*MILK), ("70 מ\"ל קצף חלבי",FOAM_ML*FOAM_MILK), ("אספרסו",ESPRESSO)])
add("צ'אי מסאלה תפוז וטוניק",[("50 מ\"ל GT",50*GT), ("150 מ\"ל טוניק",TONIC)])
add("צ'אי מסאלה פינק טוניק", [("50 מ\"ל GT",50*GT), ("150 מ\"ל טוניק",TONIC)])
add("צ'אי מסאלה ומיץ תפוזים",[("50 מ\"ל GT",50*GT), ("150 מ\"ל מיץ תפוזים",OJ)])

# 9 · קולד פואם
add("צ'אי מסאלה קולד פואם וניל",   [("50 מ\"ל GT",50*GT), ("70 מ\"ל קצף חלבי",FOAM_ML*FOAM_MILK), ("וניל",FLAV["וניל"])])
add("צ'אי מסאלה קולד פואם פיסטוק", [("50 מ\"ל GT",50*GT), ("70 מ\"ל קצף חלבי",FOAM_ML*FOAM_MILK), ("פיסטוק",FLAV["פיסטוק"])])
add("צ'אי תאילנדי קוקוס קולד פואם",[("50 מ\"ל GT",50*GT), ("150 מ\"ל מי קוקוס",150*COCO_W), ("70 מ\"ל קרם קוקוס",FOAM_ML*FOAM_COCO)])
add("צ'אי מסאלה קולד פואם בננה",   [("50 מ\"ל GT",50*GT), ("70 מ\"ל קצף חלבי",FOAM_ML*FOAM_MILK), ("בננה",FLAV["בננה"])])

# 10 · אובה — 2 גר' אובה + ⅔ חלב + קצף
UB = [("אובה 2 גר'",2*UBE), (f"{BASE:.0f} מ\"ל חלב",BASE*MILK), ("70 מ\"ל קצף חלבי",FOAM_ML*FOAM_MILK)]
for n, ing in [("אייס אובה תות","מחית תות"),("אייס אובה מנגו","מנגו"),("אייס אובה אפרסק","מחית אפרסק")]:
    add(n, UB + [(f"40 מ\"ל {ing}",40*PUREE)])
add("אייס אובה מסאלה", UB + [("50 מ\"ל GT מסאלה",50*GT)])
add("אייס אובה מאצ'ה", UB + [("מאצ'ה 1.8 גר'",1.8*MATCHA)])

if __name__ == "__main__":
    print("קצף חלבי מוכן: ₪%.2f/ליטר  |  קרם קוקוס מוכן: ₪%.2f/ליטר  |  ⅔ כוס = %d מ\"ל" % (FOAM_MILK*1000, FOAM_COCO*1000, BASE))
    print("משקאות במודל:", len(M))
